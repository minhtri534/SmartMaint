using SmartMaint.Api.Entities.Cases;

namespace SmartMaint.Api.Modules.Cases.Dtos;

// Response shapes of the Cases module. Names match frontend/src/features/cases/types.ts (camelCase JSON, snake_case enums).

public sealed record PersonResponse(long Id, string FullName);

/// <summary>FloorName is "Floor 5" (from Floors.FloorNumber), RoomName is Rooms.RoomNumber.</summary>
public sealed record LocationResponse(long BuildingId, string BuildingName, string FloorName, long RoomId, string RoomName);

public sealed record AssetResponse(long Id, string Name, long RoomId);

/// <summary>Url is short-lived (signed for 1 hour): never store it on the web side.</summary>
public sealed record PhotoResponse(long Id, string Url, CaseImageKind Kind);

public sealed record StatusChangeResponse(
    DateTimeOffset At, CaseStatus? From, CaseStatus To, PersonResponse By, string? Reason);

/// <summary>ERD: TechnicianRejections — a technician declined the assignment.</summary>
public sealed record RejectionResponse(PersonResponse Technician, DateTimeOffset RejectedAt, string Reason);

public sealed record RepairReportResponse(string RootCause, string? PartsUsed, decimal LaborHours);

public sealed record RatingResponse(int Stars, string? Comment, DateTimeOffset RatedAt);

public sealed record HoldResponse(HoldReason Reason, DateOnly ExpectedResumeOn);

/// <summary>ERD: Costs. Shown to staff, managers and the technician; to the customer only when the customer pays.</summary>
public sealed record CostResponse(long Id, string Name, string? Description, decimal Amount);

/// <summary>The customer's "not fixed" report waiting for the staff member.</summary>
public sealed record NotFixedResponse(string Reason, DateTimeOffset ReportedAt);

public sealed record TaskNoteResponse(string Note, DateTimeOffset At);

/// <summary>F2: one checklist item of a preventive work order (ERD: CaseTasks + TaskNotes + TaskImages).</summary>
public sealed record CaseTaskResponse(
    long Id,
    string Name,
    string? Description,
    Entities.Maintenance.CaseTaskStatus Status,
    IReadOnlyList<TaskNoteResponse> Notes,
    IReadOnlyList<string> PhotoUrls,
    long? RepairCaseId,
    string? RepairCaseCode);

/// <summary>One row of a case list. Requester is empty for a case generated by preventive maintenance (F2).</summary>
public record CaseSummaryResponse(
    long Id,
    string Code,
    string Title,
    CaseStatus Status,
    CasePriority Urgency,
    string ServiceTypeName,
    LocationResponse Location,
    PersonResponse? Requester,
    PersonResponse? Staff,
    PersonResponse? Technician,
    DateTimeOffset SubmittedAt,
    DateTimeOffset? DueAt,
    DateTimeOffset? SlaStartedAt,
    DateTimeOffset? CompletedAt,
    bool IsEmergencyFlow,
    bool IsPreventive);

/// <summary>
/// A whole case. <see cref="AllowedActions"/> is computed by the server for the caller (state machine + their role
/// + their buildings), so the web only draws the buttons: it never re-implements the rules.
/// </summary>
public sealed record CaseDetailResponse(
    long Id,
    string Code,
    string Title,
    CaseStatus Status,
    CasePriority Urgency,
    string ServiceTypeName,
    LocationResponse Location,
    PersonResponse? Requester,
    PersonResponse? Staff,
    PersonResponse? Technician,
    DateTimeOffset SubmittedAt,
    DateTimeOffset? DueAt,
    DateTimeOffset? SlaStartedAt,
    DateTimeOffset? CompletedAt,
    bool IsEmergencyFlow,
    bool IsPreventive,
    string Description,
    long ServiceTypeId,
    AssetResponse? Asset,
    CostBearer CostBearer,
    IReadOnlyList<PhotoResponse> Photos,
    IReadOnlyList<StatusChangeResponse> History,
    IReadOnlyList<RejectionResponse> Rejections,
    RepairReportResponse? RepairReport,
    RatingResponse? Rating,
    HoldResponse? Hold,
    IReadOnlyList<CostResponse>? Costs,
    decimal? TotalCost,
    NotFixedResponse? NotFixed,
    long? PlanId,
    IReadOnlyList<CaseTaskResponse> Tasks,
    IReadOnlyList<CaseAction> AllowedActions)
    : CaseSummaryResponse(
        Id, Code, Title, Status, Urgency, ServiceTypeName, Location, Requester, Staff, Technician,
        SubmittedAt, DueAt, SlaStartedAt, CompletedAt, IsEmergencyFlow, IsPreventive);
