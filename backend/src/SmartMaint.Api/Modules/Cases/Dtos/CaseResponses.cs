using SmartMaint.Api.Entities.Cases;

namespace SmartMaint.Api.Modules.Cases.Dtos;

// Response shapes of the Cases module. Names match frontend/src/features/cases/types.ts (camelCase JSON, snake_case enums).

public sealed record PersonResponse(long Id, string FullName);

/// <summary>FloorName is "Floor 5" (from Floors.FloorNumber), RoomName is Rooms.RoomNumber.</summary>
public sealed record LocationResponse(long BuildingId, string BuildingName, string FloorName, long RoomId, string RoomName);

public sealed record AssetResponse(long Id, string Name, long RoomId);

/// <summary>Url is short-lived (signed for 1 hour): never store it on the web side.</summary>
public sealed record PhotoResponse(long Id, string Url, CaseImageKind Kind);

public sealed record StatusChangeResponse(
    DateTimeOffset At, CaseStatus? From, CaseStatus To, PersonResponse By, string? Reason);

/// <summary>ERD: TechnicianRejections — a technician declined the assignment.</summary>
public sealed record RejectionResponse(PersonResponse Technician, DateTimeOffset RejectedAt, string Reason);

public sealed record RepairReportResponse(string RootCause, string? PartsUsed, decimal LaborHours);

public sealed record RatingResponse(int Stars, string? Comment, DateTimeOffset RatedAt);

/// <summary>ExpectedResumeOn is empty while the case waits for the staff's decision or an outside party (F5).</summary>
public sealed record HoldResponse(HoldReason Reason, DateOnly? ExpectedResumeOn);

/// <summary>ERD: Costs. Shown to staff, managers and the technician; to the customer only when the customer pays.</summary>
public sealed record CostResponse(long Id, string Name, string? Description, decimal Amount);

/// <summary>The customer's "not fixed" report waiting for the staff member.</summary>
public sealed record NotFixedResponse(string Reason, DateTimeOffset ReportedAt);

public sealed record TaskNoteResponse(string Note, DateTimeOffset At);

/// <summary>F2: one checklist item of a preventive work order (ERD: CaseTasks + TaskNotes + TaskImages).</summary>
public sealed record CaseTaskResponse(
    long Id,
    string Name,
    string? Description,
    Entities.Maintenance.CaseTaskStatus Status,
    IReadOnlyList<TaskNoteResponse> Notes,
    IReadOnlyList<string> PhotoUrls,
    long? RepairCaseId,
    string? RepairCaseCode);

/// <summary>One row of a case list. Requester is empty for a case generated by preventive maintenance (F2).</summary>
public record CaseSummaryResponse(
    long Id,
    string Code,
    string Title,
    CaseStatus Status,
    CasePriority Urgency,
    string ServiceTypeName,
    LocationResponse Location,
    PersonResponse? Requester,
    PersonResponse? Staff,
    PersonResponse? Technician,
    DateTimeOffset SubmittedAt,
    DateTimeOffset? DueAt,
    DateTimeOffset? SlaStartedAt,
    DateTimeOffset? CompletedAt,
    bool IsEmergencyFlow,
    bool IsPreventive,
    EmergencyResponse? Emergency,
    HoldReason? HoldReason,
    bool IsSurvey,
    OutsideWorkBriefResponse? OutsideWork);

/// <summary>
/// A whole case. <see cref="AllowedActions"/> is computed by the server for the caller (state machine + their role
/// + their buildings), so the web only draws the buttons: it never re-implements the rules.
/// </summary>
public sealed record CaseDetailResponse(
    long Id,
    string Code,
    string Title,
    CaseStatus Status,
    CasePriority Urgency,
    string ServiceTypeName,
    LocationResponse Location,
    PersonResponse? Requester,
    PersonResponse? Staff,
    PersonResponse? Technician,
    DateTimeOffset SubmittedAt,
    DateTimeOffset? DueAt,
    DateTimeOffset? SlaStartedAt,
    DateTimeOffset? CompletedAt,
    bool IsEmergencyFlow,
    bool IsPreventive,
    EmergencyResponse? Emergency,
    HoldReason? HoldReason,
    bool IsSurvey,
    OutsideWorkBriefResponse? OutsideWork,
    string Description,
    long ServiceTypeId,
    AssetResponse? Asset,
    CostBearer CostBearer,
    IReadOnlyList<PhotoResponse> Photos,
    IReadOnlyList<StatusChangeResponse> History,
    IReadOnlyList<RejectionResponse> Rejections,
    RepairReportResponse? RepairReport,
    RatingResponse? Rating,
    HoldResponse? Hold,
    IReadOnlyList<CostResponse>? Costs,
    decimal? TotalCost,
    NotFixedResponse? NotFixed,
    long? PlanId,
    IReadOnlyList<CaseTaskResponse> Tasks,
    IReadOnlyList<CaseRefResponse> MergedCases,
    IncidentReportResponse? IncidentReport,
    AssessmentResponse? Assessment,
    IReadOnlyList<ThirdPartyResponse> ThirdParties,
    DecisionInfoResponse? DecisionInfo,
    ReplacementResponse? Replacement,
    IReadOnlyList<CaseAction> AllowedActions)
    : CaseSummaryResponse(
        Id, Code, Title, Status, Urgency, ServiceTypeName, Location, Requester, Staff, Technician,
        SubmittedAt, DueAt, SlaStartedAt, CompletedAt, IsEmergencyFlow, IsPreventive, Emergency,
        HoldReason, IsSurvey, OutsideWork);

/// <summary>A link to another case.</summary>
public sealed record CaseRefResponse(long Id, string Code);

/// <summary>
/// F4: the 24/7 clock started at <see cref="StartedAt"/>; first response (acknowledged) and "made safe" are the two
/// milestones before "fixed" (Completed). <see cref="MergedInto"/>: this report was merged into that case (N5).
/// </summary>
public sealed record EmergencyResponse(
    DateTimeOffset StartedAt, DateTimeOffset? AcknowledgedAt, DateTimeOffset? MadeSafeAt, CaseRefResponse? MergedInto);

/// <summary>F4 step ⑫ post-incident report.</summary>
public sealed record IncidentReportResponse(string Damage, string Lessons, IncidentFollowUp FollowUp, DateTimeOffset ReportedAt);

// ----- F5 repair or replace -----------------------------------------------------------------------------------------

public sealed record AssessmentResponse(
    string Condition, string Cause, TechnicianRecommendation Recommendation, DateTimeOffset AssessedAt);

/// <summary>The latest outside party of a case, for lists.</summary>
public sealed record OutsideWorkBriefResponse(
    OutsideWorkKind Kind, OutsideWorkJob Job, OutsideWorkStatus Status, string CompanyName, DateTimeOffset? AppointmentAt);

/// <summary>One call to an outside party. StartedAt → FinishedAt is the outside phase (N16).</summary>
public sealed record ThirdPartyResponse(
    long Id,
    OutsideWorkKind Kind,
    OutsideWorkJob Job,
    OutsideWorkStatus Status,
    string CompanyName,
    string Contact,
    DateTimeOffset? AppointmentAt,
    string? Note,
    int RedoCount,
    CostBearer? QuoteBearer,
    string? QuoteSentTo,
    DateTimeOffset? QuoteSentAt,
    bool? DecisionGo,
    string? DecidedBy,
    DateTimeOffset? DecidedAt,
    string? EvidenceUrl,
    DateTimeOffset StartedAt,
    DateTimeOffset? FinishedAt);

/// <summary>
/// F5 step ③ decision board (G4, G5): facts only, no money. SuggestReplace is a hint, the staff decide (N22):
/// warranty over AND (≥ 3 repairs in 12 months OR the technician recommends replacing OR past its normal life).
/// </summary>
public sealed record DecisionInfoResponse(
    int RepairsLast12Months,
    int ReopensLast12Months,
    decimal AssetAgeYears,
    int? ExpectedLifeYears,
    DateOnly? WarrantyEndDate,
    bool UnderWarranty,
    bool ManufacturerOnly,
    string? ManufacturerName,
    string? ManufacturerPhone,
    TechnicianRecommendation? Recommendation,
    bool SuggestReplace,
    IReadOnlyList<string> Reasons);

/// <summary>The new asset written in the repair record, and where the replacement request stands.</summary>
public sealed record ReplacementResponse(string Model, string? Serial, ReplacementStatus? RequestStatus, long? NewAssetId);
